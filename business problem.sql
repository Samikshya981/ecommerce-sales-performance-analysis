use sales_order_analytics;

-- 1.Basic Sales KPIs

-- Total number of orders
SELECT count(*) AS total_orders 
from orders;

-- Total number of completed orders
SELECT count(*) AS completed_orders 
from orders 
WHERE status = 'COMPLETED';

-- Total revenue from completed orders
SELECT SUM(total_amount) AS total_revenue 
from orders 
where status = 'COMPLETED';

-- Average order value for completed orders
SELECT AVG(total_amount) AS average_order_value
 FROM orders 
 WHERE status = 'COMPLETED';
 
 -- 2. MONTHLY SALES TRENDS
 
 -- Monthly revenue 
SELECT YEAR(order_date) AS year, 
month(order_date) AS month, 
sum(total_amount) as monthly_revenue 
from orders 
where status = 'COMPLETED' 
group by year(order_date), month(order_date) 
order by year, month;

-- 3. PRODUCT ANALYSIS

-- Products with the highest number of units sold
SELECT
    p.product_id,
    p.product_name,
    SUM(oi.quantity) AS units_sold
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.status = 'COMPLETED'
GROUP BY
    p.product_id,
    p.product_name
ORDER BY
    units_sold DESC;

-- Products generating the most revenue
SELECT
    p.product_id,
    p.product_name,
    SUM(oi.quantity * oi.unit_price) AS product_revenue
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.status = 'COMPLETED'
GROUP BY
    p.product_id,
    p.product_name
ORDER BY
    product_revenue DESC;

-- Revenue generated by each product category
SELECT
    p.category,
    SUM(oi.quantity * oi.unit_price) AS category_revenue
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.status = 'COMPLETED'
GROUP BY
    p.category
ORDER BY
    category_revenue DESC;

-- Products with high sales relative to available stock
SELECT
    p.product_id,
    p.product_name,
    p.category,
    SUM(oi.quantity) AS units_sold,
    p.stock AS current_stock,
    ROUND(
        SUM(oi.quantity) / p.stock,
        2
    ) AS stock_pressure
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.status = 'COMPLETED'
GROUP BY
    p.product_id,
    p.product_name,
    p.category,
    p.stock
ORDER BY
    stock_pressure DESC;
        
-- 4. CUSTOMER ANALYSIS

-- Customers generating the most revenue from completed orders
SELECT
    c.customer_id,
    c.name,
    COUNT(DISTINCT o.order_id) AS total_orders,
    SUM(o.total_amount) AS total_revenue
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.status = 'COMPLETED'
GROUP BY
    c.customer_id,
    c.name
ORDER BY
    total_revenue DESC;

-- Customers with more than one completed order
SELECT
    c.customer_id,
    c.name,
    COUNT(o.order_id) AS completed_orders
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.status = 'COMPLETED'
GROUP BY
    c.customer_id,
    c.name
HAVING
    COUNT(o.order_id) > 1
ORDER BY
    completed_orders DESC;

-- Customer ranking based on completed-order revenue
SELECT
    c.customer_id,
    c.name,
    SUM(o.total_amount) AS total_revenue,
    RANK() OVER (
        ORDER BY SUM(o.total_amount) DESC
    ) AS revenue_rank
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.status = 'COMPLETED'
GROUP BY
    c.customer_id,
    c.name
ORDER BY
    revenue_rank;

