--  12. DATA QUALITY CHECKS

-- Check for differences between order totals and the sum of their order-item values
SELECT
    o.order_id,
    o.total_amount AS order_total,
    SUM(
        oi.quantity * oi.unit_price
    ) AS calculated_item_total,
    ROUND(
        o.total_amount
        - SUM(oi.quantity * oi.unit_price),
        2
    ) AS difference
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
GROUP BY
    o.order_id,
    o.total_amount
HAVING
    o.total_amount <> SUM(
        oi.quantity * oi.unit_price
    )
ORDER BY
    ABS(difference) DESC;
    