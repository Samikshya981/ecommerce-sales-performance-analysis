-- Payment reconciliation

-- Are there any orders where the order status, payment status, or payment amount does not match?

SELECT
    o.order_id,
    o.status AS order_status,
    o.total_amount AS order_amount,
    p.payment_status,
    p.amount AS payment_amount,
    CASE
        WHEN o.total_amount <> p.amount
            THEN 'Amount Mismatch'
        WHEN o.status = 'COMPLETED'
             AND p.payment_status <> 'PAID'
            THEN 'Status Mismatch'
        WHEN o.status = 'CANCELLED'
             AND p.payment_status <> 'REFUNDED'
            THEN 'Status Mismatch'
        WHEN o.status = 'PENDING'
             AND p.payment_status <> 'PENDING'
            THEN 'Status Mismatch'
        ELSE 'Matched'
    END AS reconciliation_status
FROM orders o
JOIN payments p
    ON o.order_id = p.order_id
ORDER BY
    reconciliation_status DESC;

-- Number of orders placed in each month
