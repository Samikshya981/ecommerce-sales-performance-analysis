    YEAR(order_date),
    MONTH(order_date)
ORDER BY
    year,
    month;
    
--  6. CANCELLATION ANALYSIS

-- Customers with cancelled orders and their cancellation rate
SELECT
    c.customer_id,
    c.name,
    COUNT(o.order_id) AS total_orders,
    SUM(
        CASE
            WHEN o.status = 'CANCELLED' THEN 1
            ELSE 0
        END
    ) AS cancelled_orders,
    ROUND(
        SUM(
            CASE
                WHEN o.status = 'CANCELLED' THEN 1
                ELSE 0
            END
        ) / COUNT(o.order_id) * 100,
        2
    ) AS cancellation_rate
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
GROUP BY
    c.customer_id,
    c.name
HAVING
    cancelled_orders > 0
ORDER BY
    cancellation_rate DESC;
 
-- Monthly cancellation rate

-- Which months are seeing the most cancelled orders?

SELECT
    YEAR(order_date) AS year,
    MONTH(order_date) AS month,
    COUNT(*) AS total_orders,
    SUM(
        CASE
            WHEN status = 'CANCELLED' THEN 1
            ELSE 0
        END
    ) AS cancelled_orders,
    ROUND(
        SUM(
            CASE
                WHEN status = 'CANCELLED' THEN 1
                ELSE 0
            END
        ) / COUNT(*) * 100,
        2
    ) AS cancellation_rate
FROM orders
GROUP BY
    YEAR(order_date),
    MONTH(order_date)
ORDER BY
    year,
    month;
    
--  Cancelled order value as a percentage of total order value
    
-- How significant is cancelled order value compared with the overall value of all orders?

SELECT
    SUM(
        CASE
            WHEN status = 'CANCELLED'
            THEN total_amount
            ELSE 0
        END
    ) AS cancelled_value,

    SUM(
        CASE
            WHEN status = 'COMPLETED'
            THEN total_amount
            ELSE 0
        END
    ) AS completed_value,

    ROUND(
        SUM(
            CASE
                WHEN status = 'CANCELLED'
                THEN total_amount
                ELSE 0
            END
        )
        / SUM(total_amount) * 100,
        2
    ) AS cancelled_value_percentage
FROM orders;

--  7. CUSTOMER BEHAVIOR & RETENTION
 
-- Customers with the highest average completed order value
SELECT
    c.customer_id,
    c.name,
    COUNT(o.order_id) AS completed_orders,
    ROUND(AVG(o.total_amount), 2) AS average_order_value
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.status = 'COMPLETED'
GROUP BY
    c.customer_id,
    c.name
ORDER BY
    average_order_value DESC;
    
-- Customers with completed orders across the highest number of months
SELECT
    c.customer_id,
    c.name,
    COUNT(
        DISTINCT DATE_FORMAT(o.order_date, '%Y-%m')
    ) AS active_months,
    COUNT(o.order_id) AS completed_orders
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.status = 'COMPLETED'
GROUP BY
    c.customer_id,
    c.name
ORDER BY
    active_months DESC,
    completed_orders DESC;
    
-- Customer type based on completed purchase behavior

-- Which customers are Never Purchased, One-Time Buyers, or Repeat Buyers?

SELECT
    c.customer_id,
    c.name,
    c.signup_date,
    COUNT(o.order_id) AS completed_orders,
    CASE
        WHEN COUNT(o.order_id) = 0
            THEN 'Never Purchased'
        WHEN COUNT(o.order_id) = 1
            THEN 'One-Time Buyer'
        ELSE 'Repeat Buyer'
    END AS customer_type
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
    AND o.status = 'COMPLETED'
GROUP BY
    c.customer_id,
    c.name,
    c.signup_date
ORDER BY
    completed_orders;
    
-- Customers who have not ordered recently and may be at risk of inactivity
SELECT
    c.customer_id,
    c.name,
    MAX(o.order_date) AS last_order_date,
    DATEDIFF(
        '2026-05-31',
        MAX(o.order_date)
    ) AS inactive_days,
    CASE
        WHEN DATEDIFF(
            '2026-05-31',
            MAX(o.order_date)
        ) >= 90 THEN 'High Risk'
        WHEN DATEDIFF(
            '2026-05-31',
            MAX(o.order_date)
        ) >= 60 THEN 'Medium Risk'
        ELSE 'Low Risk'
    END AS inactivity_risk
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
     AND o.status = 'COMPLETED'
GROUP BY
    c.customer_id,
    c.name
ORDER BY
    last_order_date ASC;

-- Customer value classification based on completed-order revenue
SELECT
    c.customer_id,
    c.name,
    COUNT(o.order_id) AS completed_orders,
    SUM(o.total_amount) AS total_revenue,
    CASE
        WHEN SUM(o.total_amount) >= 50000 THEN 'High Value'
        WHEN SUM(o.total_amount) >= 10000 THEN 'Medium Value'
        ELSE 'Low Value'
    END AS customer_value
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.status = 'COMPLETED'
GROUP BY
    c.customer_id,
    c.name
ORDER BY
    total_revenue DESC;

-- 8. ADVANCED REVENUE ANALYSIS

-- How dependent is the business on its biggest customers?
WITH customer_revenue AS (
    SELECT
        c.customer_id,
        c.name,
        SUM(o.total_amount) AS total_revenue
    FROM customers c
    JOIN orders o
        ON c.customer_id = o.customer_id
    WHERE o.status = 'COMPLETED'
    GROUP BY
        c.customer_id,
        c.name
),

ranked_customers AS (
    SELECT
        customer_id,
        name,
        total_revenue,
        RANK() OVER (
            ORDER BY total_revenue DESC
        ) AS revenue_rank
    FROM customer_revenue
)

SELECT
    ROUND(
        SUM(
            CASE
                WHEN revenue_rank <= 3
                THEN total_revenue
                ELSE 0
            END
        ),
        2
    ) AS top_3_revenue,

    ROUND(
        SUM(total_revenue),
        2
    ) AS total_completed_revenue,

    ROUND(
        SUM(
            CASE
                WHEN revenue_rank <= 3
                THEN total_revenue
                ELSE 0
            END
        )
        / SUM(total_revenue) * 100,
        2
    ) AS top_3_revenue_percentage
FROM ranked_customers;    

-- Monthly revenue change compared with the previous month
WITH monthly_sales AS (
    SELECT
        YEAR(order_date) AS year,
        MONTH(order_date) AS month,
        SUM(total_amount) AS monthly_revenue
    FROM orders
    WHERE status = 'COMPLETED'
    GROUP BY
        YEAR(order_date),
        MONTH(order_date)
)

SELECT
    year,
    month,
    monthly_revenue,

    LAG(monthly_revenue) OVER (
        ORDER BY year, month
    ) AS previous_month_revenue,

    ROUND(
        (
            monthly_revenue
            - LAG(monthly_revenue) OVER (
                ORDER BY year, month
            )
        )
        /
        LAG(monthly_revenue) OVER (
            ORDER BY year, month
        ) * 100,
        2
    ) AS revenue_change_percentage

FROM monthly_sales
ORDER BY
    year,
    month;
    
