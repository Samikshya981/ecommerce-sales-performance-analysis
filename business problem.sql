-- How much of the total order value has actually been converted into completed revenue, and how much is tied up in pending or cancelled orders?

SELECT
    status,
    COUNT(*) AS total_orders,
    SUM(total_amount) AS total_order_value,
    ROUND(
        SUM(total_amount)
        / (SELECT SUM(total_amount) FROM orders) * 100,
        2
    ) AS value_percentage
FROM orders
GROUP BY
    status
ORDER BY
    value_percentage DESC;
    
--   10. SECOND-PURCHASE ANALYSIS

-- How many days does each repeat customer take to make their second completed purchase?

WITH numbered_orders AS (
    SELECT
        customer_id,
        order_date,
        ROW_NUMBER() OVER (
            PARTITION BY customer_id
            ORDER BY order_date
        ) AS order_number
    FROM orders
    WHERE status = 'COMPLETED'
),

first_orders AS (
    SELECT
        customer_id,
        order_date AS first_order_date
    FROM numbered_orders
    WHERE order_number = 1
),

second_orders AS (
    SELECT
        customer_id,
        order_date AS second_order_date
    FROM numbered_orders
    WHERE order_number = 2
)

SELECT
    f.customer_id,
    f.first_order_date,
    s.second_order_date,
    DATEDIFF(
        s.second_order_date,
        f.first_order_date
    ) AS days_to_second_order
FROM first_orders f
JOIN second_orders s
    ON f.customer_id = s.customer_id
ORDER BY
    days_to_second_order;
    
--  11. MANAGEMENT & EXECUTIVE ANALYSIS

 -- Revenue contribution of each product
WITH product_revenue AS (
    SELECT
        p.product_id,
        p.product_name,
        SUM(oi.quantity * oi.unit_price) AS product_revenue
    FROM order_items oi
    JOIN products p
        ON oi.product_id = p.product_id
    JOIN orders o
        ON oi.order_id = o.order_id
    WHERE o.status = 'COMPLETED'
    GROUP BY
        p.product_id,
        p.product_name
)

SELECT
    product_id,
    product_name,
    product_revenue,
    ROUND(
        product_revenue /
        (SELECT SUM(product_revenue)
         FROM product_revenue) * 100,
        2
    ) AS revenue_contribution_percentage
FROM product_revenue
ORDER BY
    revenue_contribution_percentage DESC;

